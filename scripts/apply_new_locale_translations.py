def load_json(path: Path) -> dict[str, str]:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, data: dict[str, str]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=4)
        f.write("\n")


def merge_locale(lang: str, translations: dict[str, str]) -> int:
    path = LOC_DIR / f"{lang}.json"
    locale = load_json(path)
    added = 0
    for key, value in translations.items():
        if key not in locale:
            added += 1
        locale[key] = value
    write_json(path, locale)
    return added


def merge_tour_help(lang: str, translations: dict[str, str]) -> int:
    path = LOC_DIR / f"tour-help-{lang}-extra.json"
    if not path.exists():
        return 0
    tour_help = load_json(path)
    updated = 0
    for key in TOUR_HELP_KEYS:
        if key in translations:
            tour_help[key] = translations[key]
            updated += 1
    write_json(path, tour_help)
    return updated


def main() -> None:
    en = load_json(LOC_DIR / "en.json")
    en_keys = set(en.keys())

    print(f"English reference: {len(en_keys)} keys\n")

    for lang in LANGS:
        if lang not in TRANSLATIONS:
            raise SystemExit(f"Missing TRANSLATIONS entry for {lang}")

        trans = TRANSLATIONS[lang]
        added = merge_locale(lang, trans)
        tour_updated = merge_tour_help(lang, trans)

        locale = load_json(LOC_DIR / f"{lang}.json")
        missing = sorted(en_keys - set(locale.keys()))
        status = "OK" if not missing else f"MISSING {len(missing)}"
        print(
            f"{lang}: merged {len(trans)} keys, "
            f"{added} newly added to {lang}.json, "
            f"{tour_updated} tour-help keys updated — {status}"
        )
        if missing:
            for key in missing[:5]:
                print(f"  - {key}")
            if len(missing) > 5:
                print(f"  ... and {len(missing) - 5} more")


if __name__ == "__main__":
    main()
